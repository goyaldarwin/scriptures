// Protocol test of the group paath relay (worker.js), against `wrangler dev` (tools/group/README.md, "Test it here"):
//   npx wrangler dev --port 8787   (in tools/group/), then: node tools/group/test.mjs
import {execSync} from 'node:child_process';
const status = c => execSync("curl -s -o /dev/null -w '%{http_code}' -H 'Upgrade: websocket' -H 'Origin: https://evil.example' http://127.0.0.1:8787/s/" + c).toString();
const B = 'ws://127.0.0.1:8787/s/';
const open = (u) => new Promise((res, rej) => { const w = new WebSocket(u); w.msgs = []; w.closed = null; w.onmessage = e => w.msgs.push(e.data === 'pong' ? 'pong' : JSON.parse(e.data)); w.onclose = e => w.closed = e.code; w.onopen = () => res(w); w.onerror = rej; });
const sleep = ms => new Promise(r => setTimeout(r, ms));
const ok = (c, m) => { if (!c) { console.log('FAIL', m); process.exitCode = 1; } else console.log('ok  ', m); };
const code = String(100000 + Math.floor(Math.random() * 899999)), key = 'k'.repeat(10) + Math.random().toString(36).slice(2, 12).replace(/[^a-z0-9]/g, 'x');
const L = await open(B + code + '?role=lead&key=' + key); await sleep(200);
ok(L.msgs[0]?.type === 'count' && L.msgs[0].n === 0, 'leader gets count 0');
const F1 = await open(B + code + '?role=follow'); await sleep(200);
ok(F1.msgs[0]?.type === 'wait', 'follower before any state: wait');
ok(L.msgs.at(-1).n === 1, 'leader count 1');
L.send(JSON.stringify({type: 'state', s: {w: 'manas', t: 12.5, p: 1}})); await sleep(200);
ok(F1.msgs.at(-1).type === 'state' && F1.msgs.at(-1).s.t === 12.5, 'follower gets state');
const F2 = await open(B + code + '?role=follow'); await sleep(200);
ok(F2.msgs[0]?.type === 'state' && F2.msgs[0].s.w === 'manas', 'late follower gets the last state at once');
ok(L.msgs.at(-1).n === 2, 'leader count 2');
F2.send(JSON.stringify({type: 'state', s: {w: 'evil'}})); await sleep(200);
ok(F1.msgs.at(-1).s.w === 'manas', 'a follower cannot send state');
F1.send('ping'); await sleep(200); ok(F1.msgs.at(-1) === 'pong', 'ping answered');
const X = await open(B + code + '?role=lead&key=' + 'z'.repeat(20)); await sleep(300);
ok(X.msgs[0]?.type === 'taken', 'another leader key is refused');
F2.close(); await sleep(300); ok(L.msgs.at(-1).n === 1, 'count back to 1 after a follower leaves');
L.close(1000); await sleep(300);
const F3 = await open(B + code + '?role=follow'); await sleep(200);
ok(F3.msgs[0]?.type === 'state' && F3.msgs[0].s.t === 12.5, 'leader away: new follower still gets last state');
const L2 = await open(B + code + '?role=lead&key=' + key); await sleep(200);
ok(!L2.closed && L2.msgs[0].type === 'count', 'the same leader key reconnects');
L2.close(4100, 'end'); await sleep(400);
ok(F1.msgs.at(-1).type === 'end' && F1.closed === 1000, 'end reaches followers');
const L3 = await open(B + code + '?role=lead&key=' + 'y'.repeat(20)); await sleep(300);
ok(!L3.closed, 'after the end the code is free again');
L3.close(4100); F3.close();
const bad = {status: +status(code)};
ok(bad.status === 403, 'other origins refused');
process.exit();
