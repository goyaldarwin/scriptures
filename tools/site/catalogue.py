"""docs/WORKS.md: every work, by tradition and genre, with its structure, numbering, sources and recordings, in one table.

    python3 tools/site/catalogue.py        (build.py runs it; the CI fails when the committed file differs)

Made from library/ (the shelf, each work.json and its sources) and tools/works/<work>/audio/ (how each recording is
timed), so it always says what the library is: never edit docs/WORKS.md by hand. Its last section lists what is not yet
the same in every work (a meaning not given line by line, word meanings still partial, a recording not yet timed by the
forced aligner), so the gaps are seen where the works are.
"""
import glob, json, os
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
LIB = os.path.join(ROOT, 'library'); WORKS = os.path.join(ROOT, 'tools', 'works')
OUT = os.path.join(ROOT, 'docs', 'WORKS.md')
BUILTIN = {'cau': 'Chaupai', 'do': 'Doha', 'so': 'Soratha', 'cha': 'Chhand', 'shloka': 'Shloka'}

def j(p): return json.load(open(p, encoding='utf-8'))

def leaves(nodes, trail=()):
    for n in nodes:
        if 'work' in n: yield n, trail
        else: yield from leaves(n.get('children', []), trail + (n,))

def cited(w):
    """How a verse is cited, with the work's own example: the first verse whose citation has every level."""
    C = w.get('cite') or {}; by = C.get('by', ['n'])
    name = {'part': 'part', 'sec': (C.get('sec') or {}).get('en', 'section').lower(), 'n': 'verse'}
    ex = next((it for it in w['items'] if it.get('c') and it['c'].count('.') == len(by) - 1), None)
    s = '.'.join(name[x] for x in by)
    if C.get('types'): s += '; ' + ', '.join(f"{t} by {'.'.join(name[x] for x in v)}" for t, v in sorted(C['types'].items()))
    return s + (f" (`{ex['c']}`)" if ex else '')

def audio(wid, path):
    out = []
    for f in sorted(glob.glob(os.path.join(LIB, path, 'audio', '*.json'))):
        a = j(f); d = os.path.join(WORKS, wid, 'audio', a['id']); src = j(os.path.join(d, 'source.json')) if os.path.exists(os.path.join(d, 'source.json')) else {}
        how = 'taken from ' + src['take'] if src.get('take') else 'MMS' if os.path.exists(os.path.join(d, 'aligned.json')) else 'transcript'
        own = len(a.get('own') or [])
        out.append(f"{a['id']} ({how}{f', {own} by ear' if own else ''}{', draft' if a.get('draft') else ''}{', review' if src.get('review') else ''})")
    return out

def main():
    shelf = j(os.path.join(LIB, 'index.json')); langs = j(os.path.join(LIB, 'glossary', 'languages.json'))
    L = lambda c: langs.get(c, {}).get('name', {}).get('en', c)
    rows, gaps = {}, {'lines': [], 'words': [], 'mms': [], 'noaudio': []}
    for leaf, trail in leaves(shelf):
        w = j(os.path.join(LIB, leaf['path'], 'work.json')); wid = w['id']
        tradition, genre = trail[0], trail[1]
        types = {**BUILTIN, **{k: v['name']['en'] for k, v in (w.get('types') or {}).items()}}
        used = sorted({it['y'] for it in w['items']}, key=lambda t: [it['y'] for it in w['items']].index(t))
        vl = sorted({it.get('l', w['lang']) for it in w['items']}, key=lambda c: (c != w['lang'], c))
        S = w.get('sources') or {}
        mean = '; '.join(f"{k}: " + ', '.join(s['id'] for s in S[k]) for k in S if k not in ('au', 'cm') and S[k])
        if S.get('cm'): mean += '; commentary: ' + ', '.join(s['id'] for s in S['cm'])
        ours = [s for k in S if k not in ('au', 'cm') for s in S[k] if s['id'].endswith('-scriptures')]
        lines = 'yes' if ours and all(s.get('lines') for s in ours) else 'some' if any(s.get('lines') for s in ours) else 'no' if ours else '—'
        au = audio(wid, leaf['path'])
        nsec = len({it['s'] for it in w['items']})
        struct = f"{len(w['parts']['list'])} {w['parts']['name']['en'].lower()} › {nsec} sections › {len(w['items'])} verses"
        rows.setdefault((tradition['id'], tradition['title']['en']), {}).setdefault((genre['id'], genre['title']['en']), []).append(
            f"| {leaf['title']['en']} (`{wid}`) | `{leaf['path']}` | {', '.join(L(c) for c in vl)} | {struct} | {', '.join(f'{types.get(t, t)} (`{t}`)' for t in used)} | {cited(w)} | {mean or '—'} | {lines} | {'partial' if w.get('words') == 'partial' else 'every word'} | {'; '.join(au) or 'none'} |")
        if ours and lines != 'yes': gaps['lines'].append(wid)
        if w.get('words') == 'partial': gaps['words'].append(wid)
        gaps['mms'] += [f'{wid}/{x.split(" ")[0]}' for x in au if '(transcript' in x]
        if not au: gaps['noaudio'].append(wid)
    md = ['# The works', '', 'Generated by `tools/site/catalogue.py` from `library/` and `tools/works/` (`build.py` runs it); never edit it by hand.',
          'Every work is part › section › verse (`docs/LIBRARY.md` §2); a work\'s own README says why its levels are what they are.', '',
          'Columns: the work and its permanent id · its shelf path (tradition first, the same in `scriptures-data`) · the languages of its verses, the work\'s own first · its levels · its verse types · how a verse is cited (`work.json` → `cite`; the example is the work\'s own) · its meaning sources by language, the default first · whether our own meanings are given line by line · word meanings · its recordings and how their starts are timed (`tools/audio/METHOD.md`: MMS, the forced aligner, or the transcript alone; how many the owner set by ear).', '']
    for (tid, tname), genres in rows.items():
        md += [f'## {tname} (`{tid}`)', '']
        for (gid, gname), rs in genres.items():
            md += [f'### {gname} (`{tid}/{gid}`)', '', '| Work | Path | Languages | Levels | Verse types | Cited as | Meanings | Line by line | Word meanings | Recordings |', '|---|---|---|---|---|---|---|---|---|---|'] + rs + ['']
    md += ['## Not yet the same in every work', '',
           f"- **Our meanings not yet line by line** (\"Meaning per line\" shows only where they are): {', '.join(f'`{x}`' for x in gaps['lines']) or 'none'}.",
           f"- **Word meanings still partial** (`\"words\": \"partial\"`): {', '.join(f'`{x}`' for x in gaps['words']) or 'none'}.",
           f"- **Recordings timed from the transcript alone, not yet by MMS** (`tools/audio/METHOD.md`, step 2): {', '.join(f'`{x}`' for x in gaps['mms']) or 'none'}.",
           f"- **Works without a recording**: {', '.join(f'`{x}`' for x in gaps['noaudio']) or 'none'}.", '']
    text = '\n'.join(md)
    if not os.path.exists(OUT) or open(OUT, encoding='utf-8').read() != text:
        open(OUT, 'w', encoding='utf-8').write(text)
    return text

if __name__ == '__main__': main(); print('docs/WORKS.md written')
