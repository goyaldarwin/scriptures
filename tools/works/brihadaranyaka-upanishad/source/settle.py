# ---- the closing number: the printout leaves it out (1.5.6, 3.2.6, 3.9.24, 4.5.6, 6.2.15), writes a single daṇḍa
# before it (6.2.13), or prints the brāhmaṇa's number for the only mantra of a brāhmaṇa (5.11.1, 5.12.1) ----
END = re.compile(r'\s*[।॥]?\s*॥?\s*([०-९]+)\s*॥\s*$')


def mantras():
    B = json.load(open(os.path.join(HERE, 'pdf_raw.json'), encoding='utf-8'))
    a = b = 0; out = []
    for blk in B:
        if blk['kind'] == 'head':
            t = blk['rows'][0]
            if ADHYAYA.match(t): a += 1; b = 0
            elif BRAHMANA.match(t): b += 1
            continue
        if blk['kind'] != 'mantra': continue
        n = num(blk['printed']) if blk['printed'] else int(blk['ref'].split('.')[-1])
        ref = '%d.%d.%d' % (a, b, n)
        # the page's own reference, "[II.ii.9]", once names the wrong adhyāya (3.2.9): the headings decide
        if blk['ref'] != ref: assert (ref, blk['ref']) == ('3.2.9', '2.2.9'), (ref, blk['ref'])
        text = ' '.join(r['t'] for r in blk['rows'])
        if ref in NOTES_AFTER_END:
            m = list(re.finditer(r'॥\s*' + deva(n) + r'\s*॥', text))
            assert m, ref
            text = text[:m[0].end()]
        out.append({'ref': ref, 'a': a, 'b': b, 'n': n, 'text': text, 'pg': blk['pg']})
    return out


def settle_text(x):
    t = re.sub(r'\s+', ' ', re.sub(r'\s*।\s*', ' । ', x['text'])).strip()
    for wrong, right in NOTES.get(x['ref'], []) + FIX.get(x['ref'], []):
        assert t.count(wrong) == 1, (x['ref'], wrong, t)
        t = t.replace(wrong, right)
    # 3.9.28 holds seven ślokas that the printout numbers ॥१॥ … ॥७॥ inside the mantra, the last followed by the mantra's
    # own ॥२८॥: one number per verse (PLAYBOOK §3), so each śloka ends ॥ and the mantra ends ॥२८॥
    if x['ref'] == '3.9.28':
        t = re.sub(r'॥\s*७\s*॥\s*॥\s*२८\s*॥$', '॥ २८॥', t)
        t = re.sub(r'॥\s*[१-६]\s*॥', '॥', t)
        assert t.count('॥') == 8, t
    # the printout's commas (परायणꣳ, स वै) and its zero-width joiners (श‍ृ) are not kept
    t = re.sub(r'\s*,\s*', ' ', t).replace('\u200d', '')
    m = END.search(t)
    if m and num(m.group(1)) == x['n'] and not re.search(r'[।]\s*' + deva(x['n']) + r'\s*॥\s*$', t):
        pass
    elif m:     # 5.11.1, 5.12.1 (the brāhmaṇa's number), 6.2.13 (। १३॥): the mantra's own number
        t = t[:m.start()].rstrip(' ।') + ' ॥ %s॥' % deva(x['n'])
    else:       # no closing number
        t = t.rstrip(' ।॥') + ' ॥ %s॥' % deva(x['n'])
    return t


def lines(t):
    """One sentence per line: a line ends at each daṇḍa (।) and each ॥ (with its number, if it has one)."""
    parts = re.findall(r'.*?(?:॥\s*[०-९]+\s*॥|॥|।)(?:\s*॥\s*[०-९]+\s*॥)?|.+$', t)
    return [house(p) for p in parts if p.strip()]


def house(l):
    """The library's way of writing the marks: ॥ with its number inside without spaces (॥१४॥), one space before।/॥."""
    l = re.sub(r'\s*॥\s*([०-९]+)\s*॥', r' ॥\1॥', l)
    l = re.sub(r'\s*।', ' ।', l)
    l = re.sub(r'(?<![०-९])\s*॥(?![०-९])', ' ॥', l)
    return re.sub(r'\s+', ' ', l).strip()


