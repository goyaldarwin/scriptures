import re,unicodedata
def en_fix(s):
    rep=[('ì','“'),('î','”'),('í','’'),('ë','‘'),('ó','—'),('µu','ū'),('µ','ū'),('å','ā'),('Å','Ā'),('∂','ī'),('æ','r̥'),('≈','ṁ'),('¢','ṭ'),('Œ','ḍ'),('ƒ','ṇ'),('‹','ś'),('›','Ś'),('¶','ṣ'),('¨','ḥ'),('∆','ṅ'),('¤','ñ'),('°','̐')]
    for a,b in rep: s=s.replace(a,b)
    s=re.sub(r'\s+',' ',s).strip()
    s=s.replace(' ,',',').replace(' .','.')
    return unicodedata.normalize('NFC',s)
