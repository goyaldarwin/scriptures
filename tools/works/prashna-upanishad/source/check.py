EXPECTED = {name: [(a.split(), b.split()) for a, b in R] for name, R in READING.items()}

def expected(name, wit, our):
    """A difference made only of expected ones: the witness's words, each expected reading put in ours' place (whole
    words only, the longest first), are ours."""
    w, o = wit.split(), our.split()
    if any(norm(wit) == norm(' '.join(a)) and norm(our) == norm(' '.join(b)) for a, b in EXPECTED[name]): return True
    for a, b in sorted(EXPECTED[name], key=lambda r: -len(' '.join(r[0]))):
        if not a:
            if b and norm(' '.join(o[:len(b)])) == norm(' '.join(b)) and norm(' '.join(w[:len(b)])) != norm(' '.join(b)): w = b + w
            continue
        k = len(a)
        for i in range(len(w) - k + 1):
            if norm(' '.join(w[i:i + k])) == norm(' '.join(a)): w = w[:i] + b + w[i + k:]; break
    return norm(' '.join(w)) == norm(our) or norm(joined(' '.join(w))) == norm(our)

def witness(path):
    """{praśna: [words]}, {praśna: the number of verses}"""
    txt = open(path, encoding='utf-8').read()
    k, W, count = '0', {}, {}
    for blk in re.split(r'\n\s*\n', txt.strip()):
        blk = '\n'.join(l for l in blk.split('\n') if not l.startswith('# ') or re.fullmatch(r'# (\d|end)', l)).strip()
        if not blk: continue
        if blk.startswith('# '):
            k = blk[2:].strip()
            if k == 'end': break
            continue
        W.setdefault(k, []).extend(words(blk)); count[k] = count.get(k, 0) + 1
    return W, count

def convention(a, b, i1, i2, j1, j2):
    """The same words: spacing, the standard's nasals, the avagraha, or the witness's words written apart in pausa
    (GRETIL's प्रजापतिः तस्य, चन्द्रमाः । रयिः), which external sandhi joins into ours."""
    wit, our = ' '.join(a[i1:i2]), ' '.join(b[j1:j2])
    if norm(wit) == norm(our) or norm(joined(wit)) == norm(our): return True
    if i2 < len(a) and j2 < len(b) and a[i2] == b[j2]:
        return norm(joined(wit + ' ' + a[i2])) == norm(our + ' ' + b[j2])
    return False

bad = 0
for path in sorted(glob.glob(os.path.join(HERE, 'witness', '*.txt'))):
    name = os.path.basename(path); W, count = witness(path); n = 0
    for k, ow in ours(ABSENT.get(name, ())).items():
        a, b = W.get(k, []), [w for w, _ in ow]
        if not a: continue
        for op, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
            if op == 'equal': continue
            wit, our = ' '.join(a[i1:i2]), ' '.join(b[j1:j2])
            if convention(a, b, i1, i2, j1, j2): continue
            if expected(name, wit, our): continue
            n += 1; where = ow[min(j1, len(ow) - 1)][1]
            print('≠ %s %s\n  witness: %s\n  ours:    %s' % (name, where, wit or '—', our or '—'))
        mine = len({i for _, i in ow})
        if k != '0' and count[k] != mine: print('  %s praśna %s: %d mantras, ours %d' % (name, k, count[k], mine))
    print(name + ':', n, 'differences')
    bad += n
