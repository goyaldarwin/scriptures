def words(s):
    s = s.replace('ॐ', 'ओं').replace('‍', '')
    return re.sub(r'[।॥|,.¬0-9०-९\-]', ' ', s).split()

def norm(s):
    """Spacing, a nasal the standard folds (a class nasal before its stop, a final म्, ꣳ), candrabindu for anusvāra, the
    anusvāra for a doubled न or म (संनिधत्ते, सन्निधत्ते) and the avagraha (written or not: प्राणोऽग्निः, ऋचाऽभ्युक्तम्)
    are conventions, not readings."""
    s = s.replace('ँ', 'ं').replace('ऽ', '').replace('ंन', 'न्न').replace('ंम', 'म्म')
    return fold(''.join(re.sub('म्$', 'ं', w) for w in s.split()))

VOWEL = {'अ': '', 'आ': 'ा', 'इ': 'ि', 'ई': 'ी', 'उ': 'ु', 'ऊ': 'ू', 'ऋ': 'ृ', 'ए': 'े', 'ऐ': 'ै', 'ओ': 'ो', 'औ': 'ौ'}
SIGN = {v: k for k, v in VOWEL.items() if v}
CONS = set('कखगघङचछजझञटठडढणतथदधनपफबभमयरलवशषसह')

def join(a, b):
    """Two words written apart in pausa form (GRETIL: प्रजापतिः तस्य, इति एष, होवाच आकाशो) as one, by external sandhi;
    where the sandhi leaves a hiatus (स इति, देवा आ…), the space stays."""
    v = VOWEL.get(b[0])
    if a.endswith('्'):
        if a[-2] in 'कटतप' and (v is not None or b[0] in 'गघजझडढदधबभयरलव'): a = a[:-2] + 'गडदब'['कटतप'.index(a[-2])] + '्'
        return a[:-1] + v + b[1:] if v is not None else a + b
    if a.endswith('ः'):
        s, prev = a[:-1], a[-2]
        if b[0] in 'तथ': return s + 'स्' + b
        if b[0] in 'चछ': return s + 'श्' + b
        if b[0] in 'टठ': return s + 'ष्' + b
        if b[0] in 'कखपफशषस': return a + b
        if prev in CONS:
            if b[0] == 'अ': return s + 'ोऽ' + b[1:]
            return s + ' ' + b if v is not None else s + 'ो' + b
        if prev == 'ा': return s + ' ' + b
        return s + 'र्' + b if v is None else s + 'र' + v + b[1:]
    if v is None: return a + ' ' + b
    last = a[-1]
    if last in CONS or last == 'ा':
        stem = a if last in CONS else a[:-1]
        mix = {'अ': 'ा', 'आ': 'ा', 'इ': 'े', 'ई': 'े', 'उ': 'ो', 'ऊ': 'ो', 'ए': 'ै', 'ऐ': 'ै', 'ओ': 'ौ', 'औ': 'ौ'}.get(b[0])
        return stem + mix + b[1:] if mix else a + ' ' + b
    if last in 'िी' and b[0] not in 'इई': return a[:-1] + '्य' + v + b[1:]
    if last in 'ुू' and b[0] not in 'उऊ': return a[:-1] + '्व' + v + b[1:]
    return a + ' ' + b

def joined(s):
    ws = s.split()
    if not ws: return s
    out = ws[0]
    for w in ws[1:]: out = join(out, w)
    return out

ABSENT = {'iitk.txt': {'1.5', '1.7'}}   # its 1.1.5 and 1.1.7 repeat 1.6 and 1.8 (witnesses.py)

def ours(absent=()):
    """{praśna ('0' the śānti): [(word, item id)]}"""
    out = {}
    for x in ITEMS:
        if x['id'] in absent: continue
        k = '0' if x['id'] == 'shanti.1' else x['id'].split('.')[0]
        out.setdefault(k, []).extend((w, x['id']) for w in words('\n'.join(x['v'])))
    return out

