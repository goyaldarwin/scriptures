"""Checks text.txt (the Praśna Upaniṣad) against the Devanagari witnesses in source/witness/ (made by witnesses.py).

A witness file (plain text: verses separated by blank lines, each ending in ॥ N॥; a line "# 2" names the praśna the
following verses belong to; the block before the first "# 1" is the śānti mantra; "# end" starts what is after the
text, the closing śānti, which is not compared) must spell the same words as text.txt. Each praśna is compared as one
run of words, so a witness that ends a mantra elsewhere is still compared word for word, and every difference is
printed with the mantra of ours it falls in. The closing words (इति प्रश्नोपनिषदि … प्रश्नः) are not compared: the
witnesses word them differently. Daṇḍas, bars, numbers and hyphens are ignored; ॐ is read as ओं; spacing, a nasal the
library's standard folds (tools/text/standard.py → fold), candrabindu for anusvāra, the anusvāra for a doubled न or म
and the avagraha are conventions, not readings, and so are words a witness writes apart in pausa form where ours has
the sandhi (GRETIL's प्रजापतिः तस्य, इति एष): join() makes the sandhi. IIT Kanpur lacks 1.5 and 1.7 (ABSENT). The only
differences allowed are those listed in reconciliation.md (READING below).
Usage: python3 tools/works/prashna-upanishad/source/check.py
"""
